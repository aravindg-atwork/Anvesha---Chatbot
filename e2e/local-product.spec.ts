import { expect, test } from '@playwright/test';

test('real account → workspace → named project → upload → ADK processing → Qdrant answer → reload and sign in', async ({ page }) => {
  const email = `product-${Date.now()}@example.com`;
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/#/signup');
  await page.getByRole('textbox', { name: 'Your name' }).fill('Local Pilot Tester');
  await page.getByRole('textbox', { name: 'Email' }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('local-test-password');
  await page.getByRole('button', { name: 'Create account' }).click();
  await page.getByRole('textbox', { name: 'Workspace name' }).fill('Local Product Workspace');
  await page.getByRole('button', { name: 'Create workspace' }).click();
  const modal = page.getByRole('dialog', { name: 'New project' });
  await modal.getByRole('textbox', { name: 'What should it help with?' }).fill('Answer employee policy questions');
  await modal.getByRole('textbox', { name: 'Assistant name' }).fill('My Real Policy Assistant');
  await modal.getByRole('button', { name: 'Create project' }).click();
  await expect(page.getByRole('heading', { name: 'Give your assistant the information it needs.' })).toBeVisible();
  await page.getByTestId('file-input').setInputFiles({ name: 'annual-leave.txt', mimeType: 'text/plain',
    buffer: Buffer.from('Annual leave policy\nEmployees receive eighteen days of paid annual leave each year. Ask the People team to request leave.') });
  await expect(page.locator('.source-row')).toContainText('annual leave');
  await page.getByRole('button', { name: 'Continue to Training' }).click();
  await expect(page.getByRole('heading', { name: 'Your assistant is ready to test.' })).toBeVisible({ timeout: 150_000 });
  await expect(page.getByText(/passages indexed in Qdrant/).first()).toBeVisible();
  const activity = page.locator('.job-thinking').first().getByRole('button', { name: 'Thought', exact: true });
  await activity.click();
  await expect(activity).toHaveAttribute('aria-expanded', 'true');
  await expect(page.locator('.job-thinking').first()).toContainText('Indexing agent');
  await activity.press('Enter');
  await expect(activity).toHaveAttribute('aria-expanded', 'false');
  await page.screenshot({ path: 'test-results-local/training-ready.png', fullPage: true });
  await page.getByRole('button', { name: 'Continue to Try' }).click();
  await page.getByRole('radio', { name: 'Source quotes', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your question' }).fill('How many days of annual leave do employees receive?');
  await page.getByRole('textbox', { name: 'Your question' }).press('Enter');
  const answer = page.getByRole('article', { name: 'Assistant answer' }).last();
  await expect(answer).toContainText('eighteen');
  await expect(answer).toContainText('Not generated by AI');
  await expect(answer.getByRole('button', { name: 'Explain this in simple English.', exact: true })).toBeVisible();
  await answer.getByRole('button', { name: 'View sources' }).click();
  await expect(page.getByRole('complementary', { name: 'Sources for this answer' })).toContainText('eighteen');
  await page.reload();
  await expect(page.getByRole('article', { name: 'Assistant answer' }).last()).toContainText('eighteen');
  const followupRequest = page.waitForRequest((request) => request.url().endsWith('/answer') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Explain this in simple English.', exact: true }).click();
  const followupBody = (await followupRequest).postDataJSON();
  expect(followupBody.conversationId).toBeTruthy();
  expect(followupBody.messageId).toBeTruthy();
  const limitation = page.getByRole('article', { name: 'Assistant answer' }).last();
  await expect(limitation).toContainText('Source quotes mode');
  await expect(limitation).not.toContainText('eighteen days');
  await page.route(/\/api\/projects\/[^/]+\/answer$/, async (route) => {
    if (route.request().postDataJSON().engine === 'model') {
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'AI unavailable for this test. No AI reply was generated.' }) });
    } else await route.continue();
  });
  await page.getByRole('radio', { name: 'AI answers', exact: true }).click();
  const countBeforeFailure = await page.getByRole('article', { name: 'Assistant answer' }).count();
  await page.getByRole('textbox', { name: 'Your question' }).fill('Help me understand in simple English.');
  await page.getByRole('textbox', { name: 'Your question' }).press('Enter');
  await expect(page.getByText('AI unavailable for this test. No AI reply was generated.').first()).toBeVisible();
  await expect(page.getByRole('article', { name: 'Assistant answer' })).toHaveCount(countBeforeFailure);
  await page.getByRole('radio', { name: 'Source quotes', exact: true }).click();
  const privateStorage = await page.evaluate(() => localStorage.getItem('anvesha:state'));
  expect(privateStorage || '').not.toContain(email);
  await page.getByRole('link', { name: 'All projects', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page).toHaveURL(/#\/$/);
  await page.goto('/#/signin');
  await page.getByRole('textbox', { name: 'Email' }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('incorrect');
  await page.getByLabel('Password', { exact: true }).fill('local-test-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: /My Real Policy Assistant/ })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search projects' }).fill('no matching project');
  await expect(page.getByRole('heading', { name: 'No projects found' })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.getByRole('button', { name: 'List view' }).click();
  await expect(page.locator('.project-grid')).toHaveClass(/project-list-view/);
  await page.getByRole('button', { name: 'Grid view' }).click();
  await page.screenshot({ path: 'test-results-local/workspace-upgrade.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('frosted sign-in remains usable on mobile with reduced motion and no WebGL', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (this: HTMLCanvasElement, type: string, ...args: unknown[]) {
      if (type === 'webgl') return null;
      return (original as (...values: unknown[]) => unknown).call(this, type, ...args);
    } as typeof original;
  });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/signin');
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible();
  const password = page.getByLabel('Password', { exact: true });
  await password.fill('visibility-check');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(password).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await expect(password).toHaveAttribute('type', 'password');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results-local/auth-mobile-fallback.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results-local/auth-glass-desktop.png', fullPage: true });
  expect(errors).toEqual([]);
});
